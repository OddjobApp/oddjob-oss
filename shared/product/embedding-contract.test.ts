import { describe, expect, it } from "vitest";
import { cosineSimilarity, embeddingSpacesCompatible } from "./embedding-contract.js";

const descriptor = { provider: "google", model: "gemini-embedding-001", dimensions: 3, version: "1" };

describe("shared embedding contract", () => {
  it("rejects vectors generated by a different model or dimension", () => {
    expect(embeddingSpacesCompatible(descriptor, { ...descriptor, model: "other" })).toBe(false);
    expect(cosineSimilarity({ ...descriptor, vector: [1, 0, 0] }, { ...descriptor, dimensions: 2, vector: [1, 0] })).toBeNull();
  });

  it("compares vectors only within the same declared space", () => {
    expect(cosineSimilarity({ ...descriptor, vector: [1, 0, 0] }, { ...descriptor, vector: [1, 0, 0] })).toBeCloseTo(1);
    expect(cosineSimilarity({ ...descriptor, vector: [1, 0, 0] }, { ...descriptor, vector: [0, 1, 0] })).toBeCloseTo(0);
  });
});
