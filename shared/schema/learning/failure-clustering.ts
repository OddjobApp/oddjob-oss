import { pgTable, serial, text, integer, timestamp, jsonb, decimal, boolean, index } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod";
import { orgs } from '../auth.js';

/**
 * FAILURE MODE CLUSTERING
 * 
 * Automatically categorizes and clusters failures to identify
 * recurring patterns and prevent them proactively.
 */

export const failureSeverityLevels = [
  "critical",    // System outage, data loss
  "high",        // Major feature broken
  "medium",      // Degraded functionality
  "low",         // Minor issue, workaround exists
  "info",        // Observation, not necessarily failure
] as const;

export type FailureSeverity = (typeof failureSeverityLevels)[number];

export const failureDomains = [
  "agent-execution",      // Agent failed to complete task
  "tool-execution",       // Tool call failed
  "code-generation",      // Generated code has bugs
  "deployment",           // Docker/build failure
  "runtime-error",        // Code runs but errors
  "performance",          // Too slow, timeout
  "security",             // Security vulnerability
  "ux-design",            // User experience issue
  "api-integration",      // External API failure
  "database",             // DB error
  "infrastructure",       // Server/infra issue
] as const;

export type FailureDomain = (typeof failureDomains)[number];

/**
 * FAILURE INCIDENTS
 * 
 * Individual failure records with full context.
 */

export const failureIncidents = pgTable("failure_incidents", {
  id: serial("id").primaryKey(),
  organizationId: integer("organization_id").references(() => orgs.id).notNull(),
  
  // Identification
  incidentHash: text("incident_hash").notNull(), // Deterministic hash for deduplication
  
  // Classification (auto-generated by clustering engine)
  clusterId: integer("cluster_id").references(() => failureClusters.id),
  severity: text("severity").notNull().default("medium"),
  domain: text("domain").notNull(),
  subcategory: text("subcategory"), // e.g., "null-pointer", "api-timeout", "css-layout"
  
  // Error details
  errorMessage: text("error_message"),
  errorStack: text("error_stack"),
  errorCode: text("error_code"), // Structured error code if available
  
  // Context
  missionId: integer("mission_id"),
  appId: integer("app_id"),
  jobId: integer("job_id"),
  componentName: text("component_name"), // If related to a specific component
  filePath: text("file_path"), // Where the error occurred
  
  // Input that caused failure (for pattern analysis)
  triggeringInput: jsonb("triggering_input"), // Anonymized/stripped input that triggered it
  
  // Recovery
  wasResolved: boolean("was_resolved").default(false),
  resolutionMethod: text("resolution_method"), // "auto-retry", "human-intervention", "code-fix", "infra-fix"
  resolutionTimeMs: integer("resolution_time_ms"),
  
  // Prevention
  preventionRuleId: integer("prevention_rule_id"), // Rule created from this incident
  
  createdAt: timestamp("created_at").defaultNow().notNull(),
  resolvedAt: timestamp("resolved_at"),
}, (table) => ({
  orgHashIdx: index("failure_inc_org_hash_idx").on(table.organizationId, table.incidentHash),
  clusterIdx: index("failure_inc_cluster_idx").on(table.clusterId),
  domainSeverityIdx: index("failure_inc_domain_severity_idx").on(table.domain, table.severity),
  createdAtIdx: index("failure_inc_created_at_idx").on(table.createdAt),
  appIdx: index("failure_inc_app_idx").on(table.appId),
}));

export const insertFailureIncidentSchema = createInsertSchema(failureIncidents, {
  severity: z.enum(failureSeverityLevels),
  domain: z.enum(failureDomains),
}).omit({ id: true, createdAt: true, resolvedAt: true });

export type FailureIncident = typeof failureIncidents.$inferSelect;
export type InsertFailureIncident = typeof failureIncidents.$inferInsert;

/**
 * FAILURE CLUSTERS
 * 
 * Groups of similar failures identified by clustering algorithm.
 */

export const failureClusters = pgTable("failure_clusters", {
  id: serial("id").primaryKey(),
  organizationId: integer("organization_id").references(() => orgs.id).notNull(),
  
  // Cluster identity
  clusterSignature: text("cluster_signature").notNull(), // Hashed signature of the pattern
  signatureAlgorithm: text("signature_algorithm").default("semantic-embedding"), // How signature was generated
  
  // Classification
  name: text("name"), // Auto-generated descriptive name
  description: text("description"), // Auto-generated description
  severity: text("severity").notNull().default("medium"),
  domain: text("domain").notNull(),
  
  // Statistics
  incidentCount: integer("incident_count").default(0),
  firstSeenAt: timestamp("first_seen_at").defaultNow().notNull(),
  lastSeenAt: timestamp("last_seen_at").defaultNow().notNull(),
  
  // Trending
  frequency7d: decimal("frequency_7d", { precision: 5, scale: 2 }), // Incidents per day
  frequency30d: decimal("frequency_30d", { precision: 5, scale: 2 }),
  isIncreasing: boolean("is_increasing").default(false), // Frequency going up?
  
  // Root cause analysis
  likelyRootCause: text("likely_root_cause"), // LLM-generated hypothesis
  contributingFactors: jsonb("contributing_factors").default([]),
  
  // Impact
  affectedApps: jsonb("affected_apps").default([]), // Array of app IDs
  affectedMissions: jsonb("affected_missions").default([]),
  totalDowntimeMs: integer("total_downtime_ms").default(0),
  
  // Status
  status: text("status").notNull().default("active"), // "active", "mitigated", "resolved", "false-positive"
  confidenceScore: decimal("confidence_score", { precision: 5, scale: 2 }), // 0-100, clustering confidence
  
  // Resolution
  resolutionStrategy: text("resolution_strategy"), // How to fix/prevent
  preventionRuleId: integer("prevention_rule_id"),
  
  updatedAt: timestamp("updated_at").defaultNow().notNull(),
}, (table) => ({
  orgSignatureIdx: index("failure_cluster_org_sig_idx").on(table.organizationId, table.clusterSignature),
  domainSeverityIdx: index("failure_cluster_domain_sev_idx").on(table.domain, table.severity),
  statusFreqIdx: index("failure_cluster_status_freq_idx").on(table.status, table.frequency7d),
}));

export const insertFailureClusterSchema = createInsertSchema(failureClusters, {
  severity: z.enum(failureSeverityLevels),
  domain: z.enum(failureDomains),
  status: z.enum(["active", "mitigated", "resolved", "false-positive"]),
  confidenceScore: z.number().min(0).max(100).optional(),
}).omit({ id: true, firstSeenAt: true, lastSeenAt: true, updatedAt: true });

export type FailureCluster = typeof failureClusters.$inferSelect;
export type InsertFailureCluster = typeof failureClusters.$inferInsert;

/**
 * PREVENTION RULES
 * 
 * Actionable rules generated from clusters to prevent recurrence.
 */

export const preventionRuleTypes = [
  "input-validation",    // Check input before processing
  "guardrail",          // Block certain patterns
  "auto-retry",         // Automatic retry with backoff
  "fallback",           // Fallback to alternative approach
  "human-approval",     // Require human approval for risky operations
  "code-pattern-check", // Lint-like check in code generation
  "test-generation",    // Auto-generate test for this failure mode
  "circuit-breaker",    // Automatically stop calls to a failing service
  "throttling",         // Slow down calls to a service
] as const;

export type PreventionRuleType = (typeof preventionRuleTypes)[number];

export const preventionRules = pgTable("prevention_rules", {
  id: serial("id").primaryKey(),
  organizationId: integer("organization_id").references(() => orgs.id).notNull(),
  
  // Rule definition
  name: text("name").notNull(),
  description: text("description").notNull(),
  ruleType: text("rule_type").notNull(),
  
  // Matching criteria
  matchesDomain: text("matches_domain"), // Apply to specific domain
  matchesClusterId: integer("matches_cluster_id"), // Apply to specific cluster
  matchesPattern: text("matches_pattern"), // Regex or semantic pattern
  matchesComponent: text("matches_component"), // Specific component
  
  // Action configuration
  actionConfig: jsonb("action_config").notNull(), // Rule-specific configuration
  
  // Effectiveness tracking
  timesTriggered: integer("times_triggered").default(0),
  timesPrevented: integer("times_prevented").default(0), // How many incidents prevented
  falsePositiveCount: integer("false_positive_count").default(0),
  effectivenessScore: decimal("effectiveness_score", { precision: 5, scale: 2 }), // 0-100
  
  // Status
  isActive: boolean("is_active").default(true),
  isAutoGenerated: boolean("is_auto_generated").default(true),
  
  // Metadata
  createdFromClusterId: integer("created_from_cluster_id"),
  createdBy: text("created_by").notNull(), // "system", "engine", or user ID
  createdAt: timestamp("created_at").defaultNow().notNull(),
  updatedAt: timestamp("updated_at").defaultNow().notNull(),
}, (table) => ({
  orgActiveIdx: index("prevention_rule_org_active_idx").on(table.organizationId, table.isActive),
  clusterIdx: index("prevention_rule_cluster_idx").on(table.matchesClusterId),
}));

export const insertPreventionRuleSchema = createInsertSchema(preventionRules, {
  ruleType: z.enum(preventionRuleTypes),
  effectivenessScore: z.number().min(0).max(100).optional(),
}).omit({ id: true, createdAt: true, updatedAt: true });

export type PreventionRule = typeof preventionRules.$inferSelect;
export type InsertPreventionRule = typeof preventionRules.$inferInsert;


