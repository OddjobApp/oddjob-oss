/**
 * ReAct Reflection System Schema
 * 
 * Database tables for tracking agent reflections, verifications, and corrections.
 */

import { pgTable, serial, text, integer, timestamp, jsonb, decimal, boolean, index } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod";
import { orgs } from '../auth.js';

// ============================================================================
// REFLECTION LOGS
// Tracks every reflection and correction attempt
// ============================================================================

export const reflectionResolutions = ["passed", "corrected", "escalated", "failed"] as const;
export type ReflectionResolution = (typeof reflectionResolutions)[number];

export const reflectionLogs = pgTable("reflection_logs", {
  id: text("id").primaryKey(), // UUID
  
  // Context
  missionRunId: integer("mission_run_id").notNull(),
  organizationId: integer("organization_id")
    .notNull()
    .references(() => orgs.id, { onDelete: "cascade" }),
  stepId: text("step_id").notNull(),
  
  // Original output
  originalOutput: jsonb("original_output").notNull(),
  outputType: text("output_type").default("unknown"), // "text", "code", "structured", "tool_result"
  
  // Reflection results
  reflectionResult: jsonb("reflection_result").notNull(), // { verifications, issues, confidenceScore, passed }
  
  // Correction tracking
  correctionAttempted: boolean("correction_attempted").default(false),
  correctedOutput: jsonb("corrected_output"),
  correctionStrategy: text("correction_strategy"), // Which strategy was used
  
  // Retry tracking
  retryCount: integer("retry_count").default(0),
  maxRetries: integer("max_retries").default(3),
  
  // Resolution
  resolution: text("resolution").notNull(), // "passed", "corrected", "escalated", "failed"
  resolutionReason: text("resolution_reason"), // Why this resolution was chosen
  
  // Metadata
  processingTimeMs: integer("processing_time_ms"), // How long reflection took
  createdAt: timestamp("created_at").defaultNow().notNull(),
}, (table) => ({
  // Indexes for common queries
  missionRunIdx: index("reflect_log_mission_run_idx").on(table.missionRunId),
  orgResolutionIdx: index("reflect_log_org_resolution_idx").on(table.organizationId, table.resolution),
  stepIdx: index("reflect_log_step_idx").on(table.stepId),
  createdAtIdx: index("reflect_log_created_at_idx").on(table.createdAt),
  // Composite for analytics queries
  orgCreatedResolutionIdx: index("reflect_log_org_created_resolution_idx").on(
    table.organizationId, 
    table.createdAt, 
    table.resolution
  ),
}));

export const insertReflectionLogSchema = createInsertSchema(reflectionLogs, {
  resolution: z.enum(reflectionResolutions),
  outputType: z.enum(["text", "code", "structured", "tool_result", "unknown"]).optional(),
}).omit({ 
  id: true, 
  createdAt: true,
});

export type ReflectionLog = typeof reflectionLogs.$inferSelect;
export type InsertReflectionLog = typeof reflectionLogs.$inferInsert;

// ============================================================================
// REFLECTION PATTERNS
// Learned patterns for proactive corrections
// ============================================================================

export const patternTypes = [
  "hallucination", 
  "logical_error", 
  "factual_error", 
  "schema_mismatch", 
  "inconsistency",
  "common_mistake",
] as const;

export type PatternType = (typeof patternTypes)[number];

export const reflectionPatterns = pgTable("reflection_patterns", {
  id: serial("id").primaryKey(),
  organizationId: integer("organization_id")
    .notNull()
    .references(() => orgs.id, { onDelete: "cascade" }),
  
  // Pattern identification
  patternType: text("pattern_type").notNull(),
  triggerSignature: text("trigger_signature").notNull(), // Hashed pattern signature
  signatureAlgorithm: text("signature_algorithm").default("issue-hash"), // How signature was generated
  
  // Human-readable description
  name: text("name"),
  description: text("description"),
  example: text("example"), // Example of the issue
  
  // Correction strategy
  correctionStrategy: jsonb("correction_strategy").notNull(), // { type, autoFix, prompt }
  
  // Statistics
  timesDetected: integer("times_detected").default(1),
  timesCorrected: integer("times_corrected").default(0),
  timesEscalated: integer("times_escalated").default(0),
  successRate: decimal("success_rate", { precision: 5, scale: 2 }).default("0"), // 0-100
  
  // Tracking
  firstDetectedAt: timestamp("first_detected_at").defaultNow().notNull(),
  lastDetectedAt: timestamp("last_detected_at").defaultNow().notNull(),
  isActive: boolean("is_active").default(true),
  
  // Source
  createdFromLogId: text("created_from_log_id"), // Which log created this pattern
  isAutoGenerated: boolean("is_auto_generated").default(true),
}, (table) => ({
  orgSignatureIdx: index("reflect_pattern_org_sig_idx").on(table.organizationId, table.triggerSignature),
  typeIdx: index("reflect_pattern_type_idx").on(table.patternType),
  activeSuccessIdx: index("reflect_pattern_active_success_idx").on(table.isActive, table.successRate),
}));

export const insertReflectionPatternSchema = createInsertSchema(reflectionPatterns, {
  patternType: z.enum(patternTypes),
  successRate: z.number().min(0).max(100).optional(),
}).omit({ 
  id: true, 
  firstDetectedAt: true, 
  lastDetectedAt: true,
});

export type ReflectionPattern = typeof reflectionPatterns.$inferSelect;
export type InsertReflectionPattern = typeof reflectionPatterns.$inferInsert;

// ============================================================================
// REFLECTION STATISTICS (Materialized View Support)
// Pre-aggregated stats for fast dashboard queries
// ============================================================================

export const reflectionStatsDaily = pgTable("reflection_stats_daily", {
  id: serial("id").primaryKey(),
  organizationId: integer("organization_id")
    .notNull()
    .references(() => orgs.id, { onDelete: "cascade" }),
  
  date: timestamp("date").notNull(),
  
  // Counts
  totalReflections: integer("total_reflections").default(0),
  passedCount: integer("passed_count").default(0),
  correctedCount: integer("corrected_count").default(0),
  escalatedCount: integer("escalated_count").default(0),
  failedCount: integer("failed_count").default(0),
  
  // Averages
  avgConfidenceScore: decimal("avg_confidence_score", { precision: 5, scale: 2 }),
  avgProcessingTimeMs: integer("avg_processing_time_ms"),
  avgRetryCount: decimal("avg_retry_count", { precision: 3, scale: 1 }),
  
  // Issue breakdown
  hallucinationCount: integer("hallucination_count").default(0),
  logicalErrorCount: integer("logical_error_count").default(0),
  factualErrorCount: integer("factual_error_count").default(0),
  schemaMismatchCount: integer("schema_mismatch_count").default(0),
  inconsistencyCount: integer("inconsistency_count").default(0),
  
  // Token/cost tracking
  totalTokensUsed: integer("total_tokens_used"),
  estimatedCostUsd: decimal("estimated_cost_usd", { precision: 10, scale: 4 }),
  
  calculatedAt: timestamp("calculated_at").defaultNow().notNull(),
}, (table) => ({
  orgDateUniqueIdx: index("reflect_stats_org_date_unique_idx").on(table.organizationId, table.date),
}));

export type ReflectionStatsDaily = typeof reflectionStatsDaily.$inferSelect;
export type InsertReflectionStatsDaily = typeof reflectionStatsDaily.$inferInsert;


