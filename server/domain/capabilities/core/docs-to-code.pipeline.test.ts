import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";
import { promises as fs } from "node:fs";
import * as os from "node:os";
import * as path from "node:path";

import { type CapabilityManifest } from "@shared/schema/capabilities/index.js";
import { DocsToCodePipeline, isPathWithin, type DocsToCodeDeps } from "./docs-to-code.pipeline.js";
import type { ReconcileDecision } from "./capability-reconciler.service.js";

function makeManifest(id = "extract_invoice_rows"): CapabilityManifest {
    return {
        schema_version: 1,
        capability_version: "1.0.0",
        capability_id: id,
        metadata: {
            display_name: "Extract Invoice Rows",
            category: "Financial Operations",
            description: "Extract line items from an invoice image.",
            owner: "data-team",
        },
        technical_spec: { inputs: { image_url: "str" }, outputs: { rows: "list" } },
        documentation_meta: { summary: "", business_use_cases: [], guardrails: [] },
        runtime_context: { risk_profile: "Low", execution_environment: "Host", dependencies: [] },
    };
}

const APPLY_NEW: ReconcileDecision = {
    apply: true,
    isNew: true,
    reason: "new capability",
    changedFields: [],
    signatureHash: "s",
    contentHash: "c",
    changeKind: "new",
};

const IN_SYNC: ReconcileDecision = {
    apply: false,
    isNew: false,
    reason: "already in sync (signature unchanged)",
    changedFields: [],
    signatureHash: "s",
    contentHash: "c",
    changeKind: "none",
};

function makeDeps(opts: {
    fileChanged?: boolean;
    decision?: ReconcileDecision;
    extract?: () => Promise<CapabilityManifest>;
    register?: () => Promise<void>;
}) {
    const reconciler = {
        fileChanged: vi.fn(async () => opts.fileChanged ?? true),
        decide: vi.fn(async () => opts.decision ?? APPLY_NEW),
        commit: vi.fn(async () => ({ revision: 1 }) as any),
        markFile: vi.fn(async () => {}),
    };
    const registry = { register: vi.fn(opts.register ?? (async () => {})) };
    const extractor = { extract: vi.fn(opts.extract ?? (async () => makeManifest())) };
    const publisher = { publish: vi.fn(async () => {}) };
    const deps: DocsToCodeDeps = { reconciler, registry, extractor, publisher };
    return { deps, reconciler, registry, extractor, publisher };
}

describe("DocsToCodePipeline.ingestDoc", () => {
    it("skips an unchanged file before any LLM call (loop break #1)", async () => {
        const { deps, extractor, registry, reconciler } = makeDeps({ fileChanged: false });
        const result = await new DocsToCodePipeline(deps).ingestDoc(1, "docs/capabilities/x.md", "# Doc");

        expect(result.status).toBe("skipped_unchanged_file");
        expect(extractor.extract).not.toHaveBeenCalled();
        expect(registry.register).not.toHaveBeenCalled();
        expect(reconciler.markFile).not.toHaveBeenCalled();
    });

    it("registers a changed doc whose manifest is new, then marks the file", async () => {
        const { deps, registry, reconciler } = makeDeps({ decision: APPLY_NEW });
        const result = await new DocsToCodePipeline(deps).ingestDoc(9, "docs/capabilities/x.md", "# Doc changed");

        expect(result.status).toBe("registered");
        expect(result.capabilityId).toBe("extract_invoice_rows");
        expect(registry.register).toHaveBeenCalledWith(9, expect.objectContaining({ capability_id: "extract_invoice_rows" }));
        expect(reconciler.commit).toHaveBeenCalledWith(9, expect.anything(), "docs", { docMarkdown: "# Doc changed" });
        expect(reconciler.markFile).toHaveBeenCalledWith(9, "docs/capabilities/x.md", "# Doc changed");
    });

    it("does NOT re-register a doc that round-trips to the same signature (loop break #2)", async () => {
        const { deps, registry, reconciler } = makeDeps({ decision: IN_SYNC });
        const result = await new DocsToCodePipeline(deps).ingestDoc(9, "docs/capabilities/x.md", "# Regenerated by Path A");

        expect(result.status).toBe("skipped_in_sync");
        expect(registry.register).not.toHaveBeenCalled();
        expect(reconciler.commit).not.toHaveBeenCalled();
        // Still marks the file so it isn't re-extracted next scan.
        expect(reconciler.markFile).toHaveBeenCalled();
    });

    it("holds High-risk documentation changes for review instead of activating them", async () => {
        const highRisk = makeManifest();
        highRisk.runtime_context.risk_profile = "High";
        const { deps, registry, reconciler } = makeDeps({ extract: async () => highRisk });

        const result = await new DocsToCodePipeline(deps).ingestDoc(9, "docs/capabilities/x.md", "# High risk change");

        expect(result.status).toBe("review_required");
        expect(registry.register).not.toHaveBeenCalled();
        expect(reconciler.commit).not.toHaveBeenCalled();
        expect(reconciler.markFile).not.toHaveBeenCalled();
    });

    it("returns error and leaves the file UNMARKED when extraction fails (retry-safe)", async () => {
        const { deps, reconciler } = makeDeps({
            extract: async () => {
                throw new Error("model offline");
            },
        });
        const result = await new DocsToCodePipeline(deps).ingestDoc(1, "docs/capabilities/x.md", "# Doc");

        expect(result.status).toBe("error");
        expect(result.reason).toMatch(/extraction failed/);
        expect(reconciler.markFile).not.toHaveBeenCalled();
    });

    it("returns error and leaves the file UNMARKED when registration fails", async () => {
        const { deps, reconciler } = makeDeps({
            register: async () => {
                throw new Error("embedding provider down");
            },
        });
        const result = await new DocsToCodePipeline(deps).ingestDoc(1, "docs/capabilities/x.md", "# Doc");

        expect(result.status).toBe("error");
        expect(result.reason).toMatch(/embedding provider down/);
        expect(reconciler.markFile).not.toHaveBeenCalled();
    });
});

describe("DocsToCodePipeline.ingestFolder", () => {
    let repoRoot: string;

    beforeEach(async () => {
        repoRoot = await fs.mkdtemp(path.join(os.tmpdir(), "acdd-docs-"));
        await fs.mkdir(path.join(repoRoot, "docs/capabilities"), { recursive: true });
        await fs.writeFile(path.join(repoRoot, "docs/capabilities/a.md"), "# A\n", "utf8");
        await fs.writeFile(path.join(repoRoot, "docs/capabilities/b.md"), "# B\n", "utf8");
        await fs.writeFile(path.join(repoRoot, "docs/capabilities/notes.txt"), "ignore me", "utf8");
    });

    afterEach(async () => {
        await fs.rm(repoRoot, { recursive: true, force: true });
    });

    it("scans only .md files and ingests each with a repo-relative posix path", async () => {
        let counter = 0;
        const { deps } = makeDeps({ extract: async () => makeManifest(`cap_${counter++}`) });
        const pipeline = new DocsToCodePipeline(deps, {
            repoRoot,
            docsDir: path.join(repoRoot, "docs/capabilities"),
        });

        const results = await pipeline.ingestFolder(5);

        expect(results).toHaveLength(2); // notes.txt ignored
        expect(results.map((r) => r.docPath).sort()).toEqual([
            "docs/capabilities/a.md",
            "docs/capabilities/b.md",
        ]);
        expect(results.every((r) => r.status === "registered")).toBe(true);
    });

    it("rejects files outside the configured documentation root", async () => {
        const outside = path.join(repoRoot, "outside.md");
        await fs.writeFile(outside, "# Secret", "utf8");
        const { deps } = makeDeps({});
        const pipeline = new DocsToCodePipeline(deps, {
            repoRoot,
            docsDir: path.join(repoRoot, "docs/capabilities"),
        });

        await expect(pipeline.ingestFile(5, outside)).rejects.toThrow(/outside capability docs root/i);
    });
});

describe("isPathWithin", () => {
    it("accepts descendants and rejects traversal siblings", () => {
        const root = path.resolve("docs/capabilities");
        expect(isPathWithin(root, path.join(root, "safe.md"))).toBe(true);
        expect(isPathWithin(root, path.resolve(root, "../secrets.md"))).toBe(false);
    });
});
