import { Job } from "bullmq";
import { QUEUE_NAMES } from "@domain/core/infrastructure/queue/queue-service.js";
import { BaseWorker } from "@server/workers/base-worker.js";
import { db } from "@server/database_service.js";
import { knowledgeNodes, knowledgeEdges } from "@shared/schema/index.js";
import { eq, and, ne, sql, desc, inArray } from "drizzle-orm";
import { createLogger } from "@server/utils/logger.js";
import { graphService, searchNodesSemantically } from "../core/graph-service.js";

const logger = createLogger("GraphWalkerWorker");

interface GraphWalkerJobData {
    nodeId?: number; // Start walking from a specific node
    mode: "discovery" | "cleanup" | "reconciliation";
    orgContext: {
        organizationId: number | null;
        userId: string;
    };
}

export class GraphWalkerWorker extends BaseWorker<GraphWalkerJobData, any> {
    constructor() {
        super(QUEUE_NAMES.AUDIT, { // Reusing AUDIT for now or define specialized KG queue
            concurrency: 2,
            lockDuration: 600000,
        });
    }

    protected async execute(job: Job<GraphWalkerJobData>): Promise<any> {
        const { nodeId, mode, orgContext } = job.data;
        logger.info(`[GraphWalker] Starting ${mode} pass. Origin: ${nodeId || 'Full Scan'}`);

        if (mode === "discovery") {
            return await this.performDiscovery(nodeId, orgContext);
        }

        return { success: true, mode };
    }

    private async performDiscovery(nodeId: number | undefined, orgContext: any) {
        // 1. Fetch target nodes to analyze
        let targets = [];
        if (nodeId) {
            const node = await graphService.getNodeById(nodeId, orgContext);
            targets = [node];
        } else {
            // Pick recent nodes that don't have many edges
            targets = await db.select()
                .from(knowledgeNodes)
                .where(and(
                    eq(knowledgeNodes.organizationId, orgContext.organizationId || sql`NULL`),
                    sql`NOT EXISTS (SELECT 1 FROM knowledge_edges WHERE source_id = knowledge_nodes.id OR target_id = knowledge_nodes.id)`
                ))
                .limit(10)
                .orderBy(desc(knowledgeNodes.createdAt));
        }

        let relationshipsFound = 0;

        for (const node of targets) {
            logger.debug(`[GraphWalker] Analyzing semantic neighbors for node: ${node.name}`);
            
            // 2. Use vector search to find similar nodes
            const neighbors = await searchNodesSemantically(node.name, orgContext, 5);
            
            for (const neighbor of neighbors) {
                if (neighbor.id === node.id) continue;

                // 3. Check if edge already exists
                const existing = await graphService.getEdgeByNodes(node.id, neighbor.id, "RELATED_TO", orgContext);
                if (existing) continue;

                // 4. Create semantic relationship
                await graphService.createEdge({
                    sourceNodeId: node.id,
                    targetNodeId: neighbor.id,
                    relation: "SEMANTIC_SIMILARITY",
                    weight: 5,
                    properties: { autoGenerated: true, confidence: 0.8 }
                }, orgContext);
                
                relationshipsFound++;
            }
        }

        return { success: true, relationshipsFound };
    }
}

let workerInstance: GraphWalkerWorker | null = null;

export function startGraphWalkerWorker() {
    if (!workerInstance) {
        workerInstance = new GraphWalkerWorker();
    }
    return workerInstance;
}
