/**
 * Forge Security Injection Service
 *
 * Auto-injects security middleware and utilities into generated apps.
 * This ensures all Oddjob-generated applications have baseline security protections.
 *
 * Injected components:
 * - Security headers middleware (CSP, X-Frame-Options, etc.)
 * - Rate limiting utilities
 * - Input validation helpers
 * - Security utilities (sanitization, validation)
 */

import path from "node:path";
import fs from "node:fs/promises";
import { createLogger } from "@server/utils/logger.js";

const logger = createLogger("ForgeSecurityInject");

// Path to security templates
const SHARED_TEMPLATES_PATH = path.resolve("server/blueprints/apps/shared");

// Files to inject into every generated app
const SECURITY_FILES = [
  {
    source: "lib/security.ts",
    destination: "lib/security.ts",
    required: true,
  },
  {
    source: "lib/rate-limit.ts",
    destination: "lib/rate-limit.ts",
    required: true,
  },
];

// Middleware file to create if it doesn't exist
const MIDDLEWARE_CONTENT = `'use client';

/**
 * Next.js Middleware - Auto-generated by Oddjob Forge
 * Provides security headers and basic protections
 */

import { NextResponse } from 'next/server';
import type { NextRequest } from 'next/server';

export function middleware(request: NextRequest) {
  const response = NextResponse.next();
  
  // Security Headers
  response.headers.set('X-Frame-Options', 'DENY');
  response.headers.set('X-Content-Type-Options', 'nosniff');
  response.headers.set('X-XSS-Protection', '1; mode=block');
  response.headers.set('Referrer-Policy', 'strict-origin-when-cross-origin');
  response.headers.set(
    'Permissions-Policy',
    'camera=(), microphone=(), geolocation=(), payment=(), usb=(), magnetometer=(), gyroscope=(), accelerometer=()'
  );
  
  // Content Security Policy
  response.headers.set(
    'Content-Security-Policy',
    "default-src 'self'; " +
    "script-src 'self' 'unsafe-inline' 'unsafe-eval'; " +
    "style-src 'self' 'unsafe-inline'; " +
    "img-src 'self' data: https:; " +
    "font-src 'self'; " +
    "connect-src 'self' https://api.oddjob.io; " +
    "frame-ancestors 'none'; " +
    "form-action 'self';"
  );
  
  return response;
}

export const config = {
  matcher: '/:path*',
};
`;

// API route wrapper template
const API_SECURITY_WRAPPER = `import { withRateLimit } from './rate-limit';

/**
 * Security wrapper for API routes
 * Auto-applies rate limiting and security checks
 * 
 * Usage:
 * export const GET = withSecurity(async (req: Request) => {
 *   // Your handler code
 * });
 */
export function withSecurity(
  handler: (req: Request) => Promise<Response> | Response,
  options?: { rateLimit?: boolean }
) {
  if (options?.rateLimit !== false) {
    return withRateLimit(handler, {
      windowMs: 60 * 1000, // 1 minute
      maxRequests: 100,    // 100 requests per minute
    });
  }
  return handler;
}
`;

export const forgeSecurityInjectService = {
  /**
   * Inject security files into the generated app workspace
   */
  async injectSecurityFiles(
    workspacePath: string,
    emitLog?: (message: string, level?: string) => Promise<void>
  ): Promise<{ success: boolean; injected: string[]; errors: string[] }> {
    const injected: string[] = [];
    const errors: string[] = [];

    logger.info(`[ForgeSecurityInject] Injecting security files into ${workspacePath}`);

    try {
      // Copy shared security templates
      for (const file of SECURITY_FILES) {
        try {
          const sourcePath = path.join(SHARED_TEMPLATES_PATH, file.source);
          const destPath = path.join(workspacePath, file.destination);

          // Check if source exists
          try {
            await fs.access(sourcePath);
          } catch {
            if (file.required) {
              errors.push(`Required security template not found: ${file.source}`);
            }
            continue;
          }

          // Create destination directory
          await fs.mkdir(path.dirname(destPath), { recursive: true });

          // Copy file
          const content = await fs.readFile(sourcePath, "utf-8");
          await fs.writeFile(destPath, content, "utf-8");
          injected.push(file.destination);

          logger.info(`[ForgeSecurityInject] Injected ${file.destination}`);
        } catch (err: any) {
          errors.push(`Failed to inject ${file.destination}: ${err.message}`);
          logger.error(`[ForgeSecurityInject] Error injecting ${file.destination}:`, err.message);
        }
      }

      // Create middleware.ts if it doesn't exist
      const middlewarePath = path.join(workspacePath, "middleware.ts");
      try {
        await fs.access(middlewarePath);
        // Middleware exists, skip
      } catch {
        // Create middleware
        await fs.writeFile(middlewarePath, MIDDLEWARE_CONTENT, "utf-8");
        injected.push("middleware.ts");
        logger.info(`[ForgeSecurityInject] Created middleware.ts`);
      }

      // Create lib/api-security.ts for API route wrappers
      const apiSecurityPath = path.join(workspacePath, "lib", "api-security.ts");
      try {
        await fs.access(apiSecurityPath);
        // Exists, skip
      } catch {
        await fs.writeFile(apiSecurityPath, API_SECURITY_WRAPPER, "utf-8");
        injected.push("lib/api-security.ts");
        logger.info(`[ForgeSecurityInject] Created lib/api-security.ts`);
      }

      if (emitLog) {
        if (injected.length > 0) {
          await emitLog(
            `🔒 Security: Injected ${injected.length} protection modules`,
            "success"
          );
        }
        if (errors.length > 0) {
          await emitLog(
            `⚠️ Security injection issues: ${errors.length} errors`,
            "warn"
          );
        }
      }

      return {
        success: errors.length === 0 || !errors.some((e) => e.includes("Required")),
        injected,
        errors,
      };
    } catch (err: any) {
      logger.error(`[ForgeSecurityInject] Fatal error:`, err.message);
      return {
        success: false,
        injected,
        errors: [...errors, err.message],
      };
    }
  },

  /**
   * Update next.config.js to include security headers
   */
  async updateNextConfig(workspacePath: string): Promise<boolean> {
    const configPath = path.join(workspacePath, "next.config.js");

    try {
      let configContent: string;
      try {
        configContent = await fs.readFile(configPath, "utf-8");
      } catch {
        // Create default config
        configContent = `const path = require('path');
/** @type {import('next').NextConfig} */
const nextConfig = {
  webpack: (config) => {
    config.resolve.alias['react'] = path.resolve(__dirname, 'node_modules/react');
    config.resolve.alias['react-dom'] = path.resolve(__dirname, 'node_modules/react-dom');
    return config;
  }
};

module.exports = nextConfig;`;
      }

      // Check if security headers already added
      if (configContent.includes("headers: async headers()")) {
        logger.info(`[ForgeSecurityInject] Security headers already in next.config.js`);
        return true;
      }

      // Add security headers
      const securityHeaders = `,
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          {
            key: 'X-Frame-Options',
            value: 'DENY',
          },
          {
            key: 'X-Content-Type-Options',
            value: 'nosniff',
          },
          {
            key: 'Referrer-Policy',
            value: 'strict-origin-when-cross-origin',
          },
          {
            key: 'X-XSS-Protection',
            value: '1; mode=block',
          },
          {
            key: 'Permissions-Policy',
            value: 'camera=(), microphone=(), geolocation=()',
          },
        ],
      },
    ];
  },`;

      // Insert headers before the closing of nextConfig object
      const insertPosition = configContent.lastIndexOf("}");
      if (insertPosition !== -1) {
        configContent =
          configContent.slice(0, insertPosition) +
          securityHeaders +
          configContent.slice(insertPosition);
      }

      await fs.writeFile(configPath, configContent, "utf-8");
      logger.info(`[ForgeSecurityInject] Updated next.config.js with security headers`);
      return true;
    } catch (err: any) {
      logger.error(`[ForgeSecurityInject] Failed to update next.config.js:`, err.message);
      return false;
    }
  },

  /**
   * Add rate limiting to specific API routes
   */
  async addRateLimitToRoute(
    workspacePath: string,
    routePath: string,
    config?: { windowMs?: number; maxRequests?: number }
  ): Promise<boolean> {
    const fullPath = path.join(workspacePath, routePath);

    try {
      let content = await fs.readFile(fullPath, "utf-8");

      // Check if already wrapped
      if (content.includes("withRateLimit") || content.includes("withSecurity")) {
        return true;
      }

      // Add import
      const importStatement = `import { withSecurity } from '@/lib/api-security';\n`;
      content = importStatement + content;

      // Wrap handler - find export default or export async function
      if (content.includes("export default async function")) {
        // Wrap the function
        content = content.replace(
          /export default async function (\w+)/,
          "const __originalHandler = async function"
        );
        content += `\nexport default withSecurity(__originalHandler);\n`;
      } else if (content.includes("export async function GET")) {
        // Wrap individual methods
        content = content.replace(
          /export async function GET\(/,
          "const __originalGET = async function("
        );
        content += `\nexport const GET = withSecurity(__originalGET);\n`;
      }

      await fs.writeFile(fullPath, content, "utf-8");
      logger.info(`[ForgeSecurityInject] Added rate limiting to ${routePath}`);
      return true;
    } catch (err: any) {
      logger.error(
        `[ForgeSecurityInject] Failed to add rate limit to ${routePath}:`,
        err.message
      );
      return false;
    }
  },
};

export default forgeSecurityInjectService;
