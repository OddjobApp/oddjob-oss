import { createHash } from "node:crypto";
import { and, desc, eq, sql } from "drizzle-orm";
import { db } from "@server/database_service.js";
import { ForbiddenError } from '@server/utils/errors.js';
import {
  xrayOperationalConfigs,
  xrayOperationalEvents,
  xrayOperationalNotifications,
} from "@shared/schema/index.js";
import type { XrayEventEvaluation } from "../types/operational-guide.js";

export interface RecordOperationalEvaluationInput {
  organizationId: number;
  scope: string;
  evaluation: XrayEventEvaluation;
  cycleId?: number;
  missionRunId?: number;
  now?: Date;
}

function stableValue(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stableValue);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, child]) => [key, stableValue(child)]),
    );
  }
  return value;
}

export function operationalEventDeduplicationKey(evaluation: XrayEventEvaluation): string {
  const material = JSON.stringify(stableValue({
    eventType: evaluation.event.id,
    subjectNodeId: evaluation.subjectNodeId ?? null,
    evidence: evaluation.evidence,
  }));
  return createHash("sha256").update(material).digest("hex");
}

export function operationalEventDeduplicationBucket(
  now: Date,
  cooldownMinutes: number,
): string {
  const windowMs = Math.max(1, cooldownMinutes) * 60_000;
  return String(Math.floor(now.getTime() / windowMs));
}

export class XrayOperationsPersistenceService {
  async getConfig(organizationId: number, scope: string) {
    if (scope.startsWith('gmail_directive:')) throw new ForbiddenError('Gmail directives must be accessed through their owner-scoped CREW command.');
    const [record] = await db
      .select()
      .from(xrayOperationalConfigs)
      .where(and(
        eq(xrayOperationalConfigs.organizationId, organizationId),
        eq(xrayOperationalConfigs.scope, scope),
      ))
      .limit(1);
    return record ?? null;
  }

  async upsertConfig(input: {
    organizationId: number;
    scope: string;
    schemaVersion: string;
    config: Record<string, unknown>;
    updatedBy?: string;
  }) {
    if (input.scope.startsWith('gmail_directive:')) throw new ForbiddenError('Gmail directives must be managed through their owner-scoped CREW command.');
    const [record] = await db
      .insert(xrayOperationalConfigs)
      .values({
        organizationId: input.organizationId,
        scope: input.scope,
        schemaVersion: input.schemaVersion,
        config: input.config,
        updatedBy: input.updatedBy,
      })
      .onConflictDoUpdate({
        target: [xrayOperationalConfigs.organizationId, xrayOperationalConfigs.scope],
        set: {
          schemaVersion: input.schemaVersion,
          config: input.config,
          updatedBy: input.updatedBy,
          version: sql`${xrayOperationalConfigs.version} + 1`,
          updatedAt: new Date(),
        },
      })
      .returning();
    return record;
  }

  async recordEvaluation(input: RecordOperationalEvaluationInput) {
    if (input.scope.startsWith('gmail_directive:')) throw new ForbiddenError('Gmail directive events are generated by the scoped Gmail monitor.');
    const { evaluation } = input;
    const cooldownMinutes = evaluation.notification?.cooldownMinutes ?? 60;
    const now = input.now ?? new Date();
    const deduplicationKey = operationalEventDeduplicationKey(evaluation);
    const deduplicationBucket = operationalEventDeduplicationBucket(now, cooldownMinutes);

    const insertedEvents = await db
      .insert(xrayOperationalEvents)
      .values({
        organizationId: input.organizationId,
        scope: input.scope,
        cycleId: input.cycleId,
        missionRunId: input.missionRunId,
        eventType: evaluation.event.id,
        subjectNodeId: evaluation.subjectNodeId,
        severity: evaluation.event.severity,
        deduplicationKey,
        deduplicationBucket,
        evidence: evaluation.evidence,
        evaluation: evaluation as unknown as Record<string, unknown>,
        createdAt: now,
      })
      .onConflictDoNothing({
        target: [
          xrayOperationalEvents.organizationId,
          xrayOperationalEvents.scope,
          xrayOperationalEvents.deduplicationKey,
          xrayOperationalEvents.deduplicationBucket,
        ],
      })
      .returning();

    if (insertedEvents.length === 0) {
      const [existing] = await db
        .select()
        .from(xrayOperationalEvents)
        .where(and(
          eq(xrayOperationalEvents.organizationId, input.organizationId),
          eq(xrayOperationalEvents.scope, input.scope),
          eq(xrayOperationalEvents.deduplicationKey, deduplicationKey),
          eq(xrayOperationalEvents.deduplicationBucket, deduplicationBucket),
        ))
        .limit(1);
      return { event: existing, notification: null, deduplicated: true };
    }

    const event = insertedEvents[0];
    if (!evaluation.notification) {
      return { event, notification: null, deduplicated: false };
    }

    const [notification] = await db
      .insert(xrayOperationalNotifications)
      .values({
        organizationId: input.organizationId,
        scope: input.scope,
        eventId: event.id,
        ruleId: evaluation.notification.id,
        severity: evaluation.notification.severity,
        title: evaluation.event.description,
        description: evaluation.disposition.rationale,
        recipientRoles: evaluation.notification.recipientRoles,
        payload: {
          subjectNodeId: evaluation.subjectNodeId,
          copilotObjective: evaluation.notification.copilotObjective,
          closureCriteria: evaluation.notification.closureCriteria,
          context: evaluation.context,
          cycleId: input.cycleId,
          missionRunId: input.missionRunId,
        },
        createdAt: now,
        updatedAt: now,
      })
      .onConflictDoNothing()
      .returning();

    return { event, notification: notification ?? null, deduplicated: false };
  }

  async listUnreadNotifications(organizationId: number, limit = 50) {
    return db
      .select()
      .from(xrayOperationalNotifications)
      .where(and(
        eq(xrayOperationalNotifications.organizationId, organizationId),
        eq(xrayOperationalNotifications.status, "unread"),
        sql`${xrayOperationalNotifications.scope} not like 'gmail_directive:%'`,
      ))
      .orderBy(desc(xrayOperationalNotifications.createdAt))
      .limit(Math.min(100, Math.max(1, limit)));
  }

  async acknowledgeNotification(
    organizationId: number,
    notificationId: number,
    acknowledgedBy?: string,
  ) {
    const [record] = await db
      .update(xrayOperationalNotifications)
      .set({
        status: "acknowledged",
        acknowledgedBy,
        acknowledgedAt: new Date(),
        updatedAt: new Date(),
      })
      .where(and(
        eq(xrayOperationalNotifications.id, notificationId),
        eq(xrayOperationalNotifications.organizationId, organizationId),
        sql`(${xrayOperationalNotifications.scope} not like 'gmail_directive:%' or ${xrayOperationalNotifications.payload}->>'recipientUserId' = ${acknowledgedBy ?? ''})`,
      ))
      .returning();
    return record ?? null;
  }
}

export const xrayOperationsPersistenceService = new XrayOperationsPersistenceService();
