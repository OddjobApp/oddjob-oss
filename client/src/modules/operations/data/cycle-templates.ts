export interface ResourceRequirement {
    id: string;
    label: string;
    type: "url_list" | "dataset" | "credential" | "text" | "number";
    description: string;
    placeholder?: string;
    required: boolean;
}

export type DependencyOffsetUnit =
    | "ms" | "milliseconds"
    | "s" | "seconds"
    | "m" | "minutes"
    | "h" | "hours"
    | "d" | "days"
    | "w" | "weeks"
    | "M" | "months"
    | "years";

export interface Dependency {
    blueprintName: string;
    type: "finish_to_start" | "start_to_start" | "finish_to_finish" | "start_to_finish";
    offset?: {
        value: number;
        unit: DependencyOffsetUnit;
        direction: "plus" | "minus";
    };
    /** Legacy field for simple milliseconds lag */
    lagMs?: number;
}

export interface DataFlow {
    sourceBlueprint: string;
    sourceOutputKey: string;
    targetInputKey: string;
}

export interface BranchCondition {
    /** The outcome to trigger this branch: 'success' (completed) or 'failure' (failed) */
    onOutcome: "success" | "failure";
    /** The name of the blueprint to launch if this condition is met */
    targetBlueprint: string;
}

export type TimeUnit = "ms" | "s" | "m" | "h" | "d" | "w" | "M";

export interface Blueprint {
    name: string;
    objective: string;
    /** 'mission' is executable work, 'milestone' is a zero-duration strategic checkpoint, 'prediction' is a predictive analysis task */
    type: "mission" | "milestone" | "prediction";
    /** Advanced Gantt relationships */
    dependencies?: Dependency[];
    /** Strategic Branching: Pivot the cycle based on mission outcomes */
    branches?: BranchCondition[];
    /** For Milestones: Should the cycle pause for human 'Go/No-Go' approval? */
    pauseAtMilestone?: boolean;
    /** Defined data requirements for this blueprint */
    inputs?: string[];
    /** Defined data products generated by this blueprint */
    outputs?: string[];
    /** Mapping of how data flows from previous blueprints into this one */
    dataFlows?: DataFlow[];
    resources?: ResourceRequirement[];
    /** Estimated working days to complete this phase — used by the Gantt CPM engine */
    estimatedDays?: number;
    /** Estimated duration in selected unit */
    estimatedDuration?: number;
    /** Time resolution unit */
    timeUnit?: TimeUnit;
    /** Historical average runtime in milliseconds */
    avgRuntime?: number;
    /** Manual scheduling constraint: earliest start in days/units from cycle Day 0.
     *  Set by dragging in the Gantt chart. CPM will use max(computed_ES, scheduledStart). */
    scheduledStart?: number;
    /** Optional runtime trigger metadata surfaced in cycle detail. */
    trigger?: any;
    /** Legacy support for simple sequential dependencies */
    dependsOn?: string[];
    /** Custom configuration for specialized blueprints (e.g. prediction) */
    config?: {
        hf_dataset?: string;
        feature_mapping_string?: string;
        [key: string]: any;
    };
}

