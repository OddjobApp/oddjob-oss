// @ts-nocheck

import "dotenv/config";
import { db } from "../../server/db/index.js";
import { adminService } from "../../server/domain/admin/admin.service";
import jobService from "../../server/domain/jobs/job.service";
import { pipelineService } from "@domain/tools/v1/capabilities/core.js";
import { pipelineExecutor } from "../../server/core/pipeline-executor";
import { knowledgeTopics, jobs, pipelines, pipelineSteps, orgSettings } from "@shared/schema";
import { eq } from "drizzle-orm";

async function run() {
    console.log("Starting Knowledge Data Population...");

    // 1. Get Organization
    const { orgs } = await import("@shared/schema");
    let [org] = await db.select().from(orgs).limit(1);

    if (!org) {
        console.log("No organization found, creating one...");
        [org] = await db.insert(orgs).values({
            name: "E2E Test Org"
        }).returning();
    }
    const orgId = org.id;
    console.log(`Using Org ID: ${orgId}`);

    // Ensure Org Settings allow Knowledge Graph
    console.log("Checking Org Settings...");
    try {
        const existingSettings = await adminService.getOrgSettings(orgId);
        if (!existingSettings) {
            await adminService.updateOrgSettings(orgId, { knowledgeGraphEnabled: true, knowledgeStoreEnabled: true });
        } else if (!existingSettings.knowledgeGraphEnabled || !existingSettings.knowledgeStoreEnabled) {
            await adminService.updateOrgSettings(orgId, { knowledgeGraphEnabled: true, knowledgeStoreEnabled: true });
        }
    } catch (e) {
        console.warn("Could not update org settings, assuming defaults:", e);
    }

    // 2. Create Topic
    console.log("Creating Knowledge Topic...");
    const topicName = "E2E Test Products";
    let [topic] = await db.select().from(knowledgeTopics).where(eq(knowledgeTopics.name, topicName)).limit(1);

    if (!topic) {
        [topic] = await db.insert(knowledgeTopics).values({
            name: topicName,
            description: "Generated by E2E script",
            organizationId: orgId,
            createdBy: "system"
        }).returning();
    }
    console.log(`Topic ID: ${topic.id}`);

    // 3. Create Job
    console.log("Creating Shell Job...");
    const sampleData = [
        { "id": "PROD-001", "name": "Quantum Toaster", "category": "Home", "price": 199.99, "description": "Toasts bread using quantum superposition." },
        { "id": "PROD-002", "name": "Hyper-Speed Blender", "category": "Home", "price": 89.99, "description": "Blends at mach 3." },
        { "id": "PROD-003", "name": "Neural Network Coffee Maker", "category": "Office", "price": 299.00, "description": "Predicts when you want coffee." }
    ];

    const jobName = `E2E Data Gen ${Date.now()}`;
    const job = await jobService.create({
        name: jobName,
        type: "shell",
        lifecycleStatus: "active",
        description: "Generates sample product data via shell",
        tool: "None",
        config: {
            executable: "echo",
            parameters: `'${JSON.stringify(sampleData)}'`
        },
        enableKnowledgeStore: true,
        outputKnowledgeTopicId: topic.id,
        outputTags: ["generated"]
    }, { userId: 'system', organizationId: orgId });
    console.log(`Job Created: ${job.id}`);

    // 4. Create Pipeline
    console.log("Creating Pipeline...");
    const pipeline = await pipelineService.create({
        name: `Knowledge Population Pipeline ${Date.now()}`,
        description: "Populates knowledge graph",
        triggerType: "manual",
        steps: [
            {
                jobId: job.id,
                order: 1,
                knowledgeGraphConfig: {
                    extractFromSteps: [], // Empty means all valid steps
                    entityRules: [
                        {
                            entityType: "product",
                            label: "Product",
                            mappings: {
                                name: "name",
                                externalId: "id",
                                data: { category: "category", price: "price", description: "description" }
                            }
                        }
                    ],
                    relationshipRules: [],
                    autoCreate: true,
                    linkToKnowledgeDocuments: true
                }
            }
        ],
    }, { userId: "system", organizationId: orgId, isAdmin: true, isSuperAdmin: true, isOrgAdmin: true });

    console.log(`Pipeline Created: ${pipeline.id}`);

    // 5. Execute
    console.log("Executing Pipeline...");
    // No need for input now, shell job ignores it (unless used in params)
    const result = await pipelineExecutor.executePipeline(pipeline.id, "system");

    console.log(`Execution Started: ${result.executionId}`);
    if (!result.success) {
        console.error("Execution Failed Immediately:", result.error);
        process.exit(1);
    }

    // 6. Verify Output
    console.log("Execution Completed. Verifying Data...");

    // Check Nodes
    const { knowledgeNodes } = await import("@shared/schema");
    const nodes = await db.select().from(knowledgeNodes).where(eq(knowledgeNodes.organizationId, orgId));
    const newNodes = nodes.filter(n => n.label === "Product");
    console.log(`Found ${newNodes.length} 'Product' nodes in Knowledge Graph.`);

    if (newNodes.length > 0) {
        console.log("Sample Node:", newNodes[0]);
    } else {
        console.log("No nodes found. Checking Pipeline Execution record...");
        // maybe verify step result?
        if (result.stepResults && result.stepResults.length > 0) {
            console.log("Step Output:", result.stepResults[0].output);
        }
    }

    console.log("Done.");
    process.exit(0);
}

run().catch(e => {
    console.error("Fatal Error:", e);
    process.exit(1);
});
